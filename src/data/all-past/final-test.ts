export const PAST_FINAL_SIZE = 20;

/** Набор из 20 заданий для конкретной попытки. */
export function pastFinalTestFor(attempt: number): Exercise[] {
  const bank = PAST_FINAL_BANK;
  const offset = (attempt * 4) % bank.length;
  return Array.from(
    { length: PAST_FINAL_SIZE },
    (_, i) => bank[(offset + i) % bank.length] as Exercise,
  );
}
