export const FINAL_TEST_SIZE = 20;

/** Набор из 20 заданий для конкретной попытки (сдвиг по банку, без повторов внутри попытки). */
export function finalTestFor(attempt: number): Exercise[] {
  const bank = FINAL_TEST_BANK;
  const offset = (attempt * 4) % bank.length;
  return Array.from(
    { length: FINAL_TEST_SIZE },
    (_, i) => bank[(offset + i) % bank.length] as Exercise,
  );
}
